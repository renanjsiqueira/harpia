package dev.harpia.target.javaspring;

import static org.assertj.core.api.Assertions.assertThat;

import dev.harpia.CompileRequest;
import dev.harpia.CompileResult;
import dev.harpia.HarpiaCompiler;
import dev.harpia.emit.GeneratedTree;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;

class LogicEmitterTest {

    private static final String DISCOUNT =
            "src/main/java/com/example/pricing/logic/CalculateDiscount.java";
    private static final String TOTAL =
            "src/main/java/com/example/pricing/logic/CalculateTotal.java";

    @Test
    void emitsOnePureClassPerLogicUnderTheLogicPackage() {
        GeneratedTree tree = compile().tree().orElseThrow();

        assertThat(tree.files().keySet()).contains(DISCOUNT, TOTAL);
        assertThat(tree.files().get(DISCOUNT))
                .startsWith("// Generated by Harpia. Do not edit.\n")
                .contains("package com.example.pricing.logic;")
                .contains("public final class CalculateDiscount")
                .contains("private CalculateDiscount() {")
                .contains("public static BigDecimal apply(BigDecimal total, Boolean vip)");
    }

    @Test
    void pureLogicNeverDependsOnSpring() {
        String source = compile().tree().orElseThrow().files().get(DISCOUNT);

        assertThat(source)
                .doesNotContain("org.springframework")
                .doesNotContain("@Service")
                .doesNotContain("@Component")
                .doesNotContain("Autowired");
    }

    @Test
    void decimalsUseExactBigDecimalAndNeverBinaryFloatingPoint() {
        String source = compile().tree().orElseThrow().files().get(DISCOUNT);

        assertThat(source)
                .contains("import java.math.BigDecimal;")
                .contains("total.multiply(new BigDecimal(\"0.20\"))")
                .contains("total.compareTo(new BigDecimal(\"1000\")) >= 0")
                .doesNotContain("double")
                .doesNotContain("float");
    }

    @Test
    void aCallToAnotherLogicBecomesAPlainStaticCallInTheSamePackage() {
        String source = compile().tree().orElseThrow().files().get(TOTAL);

        assertThat(source)
                .contains("final BigDecimal discount = CalculateDiscount.apply(subtotal, vip);")
                .contains("final BigDecimal capped = "
                        + "discount.min(subtotal.multiply(new BigDecimal(\"0.15\")));")
                .contains("return subtotal.subtract(capped).add(shipping);");
    }

    @Test
    void repeatedCompilationProducesTheSameBytes() {
        assertThat(compile().tree().orElseThrow().files())
                .isEqualTo(compile().tree().orElseThrow().files());
    }

    private static CompileResult compile() {
        CompileResult result = new HarpiaCompiler().compile(
                new CompileRequest(Path.of("examples/business-logic/pricing")));
        assertThat(result.diagnostics()).isEmpty();
        return result;
    }
}
