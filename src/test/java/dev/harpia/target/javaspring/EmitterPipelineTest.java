package dev.harpia.target.javaspring;

import static org.assertj.core.api.Assertions.assertThat;

import dev.harpia.CompileRequest;
import dev.harpia.CompileResult;
import dev.harpia.HarpiaCompiler;
import dev.harpia.emit.GeneratedTree;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;

class EmitterPipelineTest {

    @Test
    void canonicalExampleEmitsBasicSpringProjectFromProviderContributions() {
        CompileResult result = compileExample();

        assertThat(result.hasErrors()).isFalse();
        GeneratedTree tree = result.tree().orElseThrow();
        assertThat(tree.files().keySet()).containsExactly(
                "pom.xml",
                "src/main/java/com/example/customer/CustomerServiceApplication.java",
                "src/main/java/com/example/customer/domain/Customer.java",
                "src/main/java/com/example/customer/dto/CreateCustomerRequest.java",
                "src/main/java/com/example/customer/dto/CustomerResponse.java",
                "src/main/java/com/example/customer/dto/UpdateCustomerRequest.java",
                "src/main/java/com/example/customer/error/ApiError.java",
                "src/main/java/com/example/customer/error/ApiExceptionHandler.java",
                "src/main/java/com/example/customer/error/NotFoundException.java",
                "src/main/java/com/example/customer/repository/CustomerRepository.java",
                "src/main/java/com/example/customer/service/CustomerService.java",
                "src/main/java/com/example/customer/web/CustomerController.java",
                "src/main/resources/application.yaml",
                "src/main/resources/db/migration/V1__init.sql",
                "src/test/java/com/example/customer/service/CustomerServiceTest.java",
                "src/test/java/com/example/customer/web/CustomerControllerTest.java");

        assertThat(tree.files().get("pom.xml"))
                .startsWith("<!-- Generated by Harpia. Do not edit. -->\n")
                .contains("<version>3.3.6</version>")
                .contains("<artifactId>spring-boot-starter-web</artifactId>")
                .contains("<artifactId>spring-boot-starter-data-jpa</artifactId>")
                .contains("<artifactId>flyway-database-postgresql</artifactId>")
                .contains("<artifactId>postgresql</artifactId>")
                .contains("<scope>runtime</scope>")
                .contains("<artifactId>spring-boot-starter-test</artifactId>")
                .contains("<scope>test</scope>");

        assertThat(tree.files().get(
                        "src/main/java/com/example/customer/CustomerServiceApplication.java"))
                .contains("package com.example.customer;")
                .contains("public class CustomerServiceApplication")
                .contains("SpringApplication.run(CustomerServiceApplication.class, args);");

        assertThat(tree.files().get("src/main/resources/application.yaml"))
                .contains("spring.application.name: \"customer-service\"")
                .contains("spring.datasource.url: \"${DATABASE_URL}\"")
                .contains("spring.jpa.hibernate.ddl-auto: \"validate\"")
                .contains("spring.flyway.enabled: \"true\"");
        assertThat(tree.files().values()).allSatisfy(content -> {
            assertThat(content).doesNotContain("\r");
            assertThat(content).matches("(?s).*(?<![ \\t])\\n$");
            assertThat(content).doesNotContain("\n\n\n");
        });
    }

    @Test
    void repeatedCompilationProducesTheSamePathsAndBytes() {
        CompileResult first = compileExample();
        CompileResult second = compileExample();

        assertThat(second.tree().orElseThrow().files())
                .isEqualTo(first.tree().orElseThrow().files());
    }

    private static CompileResult compileExample() {
        return new HarpiaCompiler().compile(
                new CompileRequest(Path.of("examples/customer")));
    }
}
