package dev.harpia.target.javaspring.renderer;

import static org.assertj.core.api.Assertions.assertThat;

import dev.harpia.diag.SourceRef;
import dev.harpia.emit.GeneratedFile;
import dev.harpia.target.javaspring.model.JavaAnnotationModel;
import dev.harpia.target.javaspring.model.JavaFieldModel;
import dev.harpia.target.javaspring.model.JavaMethodModel;
import dev.harpia.target.javaspring.model.JavaParameterModel;
import dev.harpia.target.javaspring.model.JavaSourceFile;
import dev.harpia.target.javaspring.model.JavaTypeModel;
import dev.harpia.target.javaspring.model.JavaTypeRef;
import dev.harpia.target.javaspring.model.JavaVisibility;
import java.util.List;
import java.util.Optional;
import java.util.Set;
import org.junit.jupiter.api.Test;

class JavaSourceRendererTest {

    @Test
    void rendersAResolvedModelWithoutKnowingAnyHarpiaFlags() {
        SourceRef typeSource = SourceRef.span("spec/greeting.harpia.md", 1, 1, 1, 11);
        SourceRef methodSource = SourceRef.span("bindings/http.harpia.md", 7, 1, 7, 21);
        JavaTypeModel type = new JavaTypeModel(
                JavaTypeModel.Kind.CLASS,
                "com.example",
                "Greeting",
                JavaVisibility.PUBLIC,
                Set.of(),
                Optional.of("A deterministic greeting."),
                List.of(JavaAnnotationModel.marker("org.example.Component")),
                List.of(),
                List.of(),
                List.of(new JavaFieldModel(
                        "message",
                        JavaTypeRef.of("java.lang.String"),
                        JavaVisibility.PRIVATE,
                        Set.of(),
                        List.of(),
                        Optional.empty(),
                        Optional.empty())),
                List.of(),
                List.of(new JavaMethodModel(
                        "greet",
                        JavaTypeRef.of("java.lang.String"),
                        JavaVisibility.PUBLIC,
                        Set.of(),
                        List.of(),
                        List.of(new JavaParameterModel(
                                "name", JavaTypeRef.of("java.lang.String"))),
                        List.of("return message + name;"),
                        Optional.of(methodSource))),
                Optional.of(typeSource));

        GeneratedFile generated = new JavaSourceRenderer().render(new JavaSourceFile(
                "src/main/java/com/example/Greeting.java", type, Optional.of(typeSource)));
        String source = generated.content();

        assertThat(source).isEqualTo("""
                // Generated by Harpia. Do not edit.
                package com.example;

                import org.example.Component;

                /**
                 * A deterministic greeting.
                 */
                @Component
                public class Greeting {

                    private String message;

                    public String greet(String name) {
                        return message + name;
                    }
                }
                """);
        assertThat(generated.sourceMappings()).hasSize(2);
        assertThat(generated.sourceMappings().get(0)).satisfies(mapping -> {
            assertThat(mapping.symbol()).isEqualTo("com.example.Greeting");
            assertThat(mapping.source()).isEqualTo(typeSource);
            assertThat(mapping.generated().describe())
                    .isEqualTo("src/main/java/com/example/Greeting.java:6:1-18:1");
        });
        assertThat(generated.sourceMappings().get(1)).satisfies(mapping -> {
            assertThat(mapping.symbol()).isEqualTo("com.example.Greeting#greet");
            assertThat(mapping.source()).isEqualTo(methodSource);
            assertThat(mapping.generated().describe())
                    .isEqualTo("src/main/java/com/example/Greeting.java:14:1-17:1");
        });
    }
}
